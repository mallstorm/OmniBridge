param([string]$Root)
$ErrorActionPreference='Stop'
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path) }
. (Join-Path $Root 'scripts\security.ps1')
$configPath=Join-Path $Root 'data\config.json'
if(-not(Test-Path $configPath)){throw 'Сначала запустите setup.cmd.'}
$c=Get-BridgeConfig $Root
$h=@{Authorization="Bearer $($c.admin_api_key)"}
$dataKey=[string]$c.data_api_key
if([string]::IsNullOrWhiteSpace($dataKey)){throw 'Локальный Bridge Key отсутствует.'}

# Verify the exact key that will be written to VS Code against the running Core.
# This catches stale/foreign data folders before we create a broken provider entry.
try{
    $null=Invoke-RestMethod -Uri 'http://127.0.0.1:4142/v1/models' -Headers @{'x-bridge-key'=$dataKey} -TimeoutSec 10
}catch{throw 'Текущий LOCAL BRIDGE KEY не принимается запущенным Core. Перезапустите OmniBridge и повторите синхронизацию. '+$_.Exception.Message}

# VS Code Custom Endpoint export v2 is generated by Core. This keeps the
# picker contract (including auto/* virtual models) in one tested place.
$export=Invoke-RestMethod -Uri 'http://127.0.0.1:4142/bridge/vscode/export' -Headers $h -TimeoutSec 30
if($export.bridge_key_fingerprint){
    $sha=[Security.Cryptography.SHA256]::Create()
    try{$localFp=([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($dataKey)))).Replace('-','').ToLowerInvariant().Substring(0,16)}finally{$sha.Dispose()}
    if($localFp -ne [string]$export.bridge_key_fingerprint){throw 'UI и Core используют разные LOCAL BRIDGE KEY. Выполните перезапуск/Repair OmniBridge.'}
}
$models=@()
foreach($m in @($export.models)){
    if(-not$m.id -or -not$m.url -or @('messages','responses','chat-completions') -notcontains [string]$m.apiType){continue}
    $x=[ordered]@{
        id=[string]$m.id
        name=[string]$m.name
        url=[string]$m.url
        apiType=[string]$m.apiType
        toolCalling=[bool]$m.toolCalling
        vision=[bool]$m.vision
        streaming=if($null-ne$m.streaming){[bool]$m.streaming}else{$true}
        # Keep the local key in one provider field only. VS Code substitutes ${apiKey}
        # for every model request, avoiding one plaintext copy per exported model.
        requestHeaders=[ordered]@{Authorization='Bearer ${apiKey}';'x-bridge-key'='${apiKey}'}
    }
    if($null-ne$m.thinking -and [bool]$m.thinking){$x.thinking=$true}
    if($null-ne$m.contextWindow -and [int64]$m.contextWindow -gt 0){$x.contextWindow=[int64]$m.contextWindow}
    if($null-ne$m.maxInputTokens -and [int64]$m.maxInputTokens -gt 0){$x.maxInputTokens=[int64]$m.maxInputTokens}
    if($null-ne$m.maxOutputTokens -and [int64]$m.maxOutputTokens -gt 0){$x.maxOutputTokens=[int64]$m.maxOutputTokens}
    $models += [pscustomobject]$x
}
if(-not$models.Count){throw 'OmniBridge не нашёл моделей, пригодных для экспорта в VS Code.'}

# Current VS Code Custom Endpoint requires vendor=customendpoint. Keep an
# explicit provider-level API type as a compatibility default; each physical
# model can still override it with Messages or Responses.
$provider=[pscustomobject][ordered]@{
    name='OmniBridge'
    vendor='customendpoint'
    apiKey=$dataKey
    apiType='chat-completions'
    models=$models
}

$userDir=Join-Path $env:APPDATA 'Code\User'
New-Item -ItemType Directory -Force -Path $userDir|Out-Null
$file=Join-Path $userDir 'chatLanguageModels.json'
$existing=@()
if(Test-Path $file){
    Copy-Item $file ($file+'.backup-'+(Get-Date -Format 'yyyyMMdd-HHmmss'))
    try{
        $raw=Get-Content -Raw -LiteralPath $file
        if(-not[string]::IsNullOrWhiteSpace($raw)){$existing=@($raw|ConvertFrom-Json)}
    }catch{throw "Не удалось прочитать $file : $($_.Exception.Message)"}
}
function Test-OldOmniBridgeProvider($p){
    if($null -eq $p -or [string]$p.vendor -ne 'customendpoint'){return $false}
    if([string]$p.name -eq 'OmniBridge' -or [string]$p.name -eq 'Universal Bridge'){return $true}
    foreach($m in @($p.models)){
        $u=[string]$m.url
        if($u -match '^https?://(127\.0\.0\.1|localhost):4142(/|$)'){return $true}
    }
    return $false
}
$out=@($existing|Where-Object{-not (Test-OldOmniBridgeProvider $_)})
$out += $provider
$json=$out|ConvertTo-Json -Depth 30
[IO.File]::WriteAllText($file,$json,(New-Object Text.UTF8Encoding($false)))

# Read-back contract: the preflight-validated local key is stored once at provider
# level and model headers use VS Code's ${apiKey} substitution.
$verify=@((Get-Content -Raw -LiteralPath $file|ConvertFrom-Json)|Where-Object{$_.name -eq 'OmniBridge' -and $_.vendor -eq 'customendpoint'}|Select-Object -Last 1)
if(-not$verify.Count){throw 'VS Code provider OmniBridge не записан.'}
if([string]$verify[0].apiKey -ne $dataKey){throw 'VS Code provider записан с неверным локальным ключом.'}
foreach($vm in @($verify[0].models)){
    if([string]$vm.requestHeaders.Authorization -ne 'Bearer ${apiKey}'){throw ('Неверный Authorization у модели '+[string]$vm.id)}
    if([string]$vm.requestHeaders.'x-bridge-key' -ne '${apiKey}'){throw ('Неверный x-bridge-key у модели '+[string]$vm.id)}
}

# BYOK models in the agent host are opt-in in current VS Code. Safe-merge the
# documented switch without touching unrelated user settings.
$settings=Join-Path $userDir 'settings.json'
try{
    $obj=[ordered]@{}
    if(Test-Path $settings){$txt=Get-Content -Raw -LiteralPath $settings;if(-not[string]::IsNullOrWhiteSpace($txt)){$parsed=$txt|ConvertFrom-Json;foreach($pp in $parsed.PSObject.Properties){$obj[$pp.Name]=$pp.Value}}}
    $obj['chat.agentHost.byokModels.enabled']=$true
    [IO.File]::WriteAllText($settings,($obj|ConvertTo-Json -Depth 30),(New-Object Text.UTF8Encoding($false)))
}catch{Write-Warning ('Не удалось включить chat.agentHost.byokModels.enabled: '+$_.Exception.Message)}

$agentCount=@($models|Where-Object{$_.toolCalling}).Count
$autoCount=@($models|Where-Object{([string]$_.id).StartsWith('auto/')}).Count
Write-Host "OmniBridge: синхронизировано моделей: $($models.Count) (Agent picker: $agentCount, auto/*: $autoCount)" -ForegroundColor Green
Write-Host ("Пропущено непроверенных/несовместимых моделей: {0}" -f [int]$export.models_skipped) -ForegroundColor Yellow
foreach($reason in @($export.skipped_reasons.PSObject.Properties|Select-Object -First 12)){Write-Host ("  {0}: {1}" -f$reason.Name,$reason.Value) -ForegroundColor DarkGray}
Write-Host "Файл: $file"
Write-Host 'VS Code нужно полностью перезапустить после синхронизации.' -ForegroundColor Yellow
Write-Host 'LOCAL BRIDGE KEY хранится в provider.apiKey один раз; модели используют ${apiKey}. Это локальный ключ шлюза, не ключ облачного провайдера.' -ForegroundColor DarkGray
Write-Host 'Если модели видны в Manage Models, но отсутствуют в Chat picker, включите значок глаза (Visibility) у моделей OmniBridge: VS Code хранит эту видимость отдельно от chatLanguageModels.json.' -ForegroundColor Yellow
if([int]$export.agent_picker_models -eq 0){
    Write-Warning 'Нет моделей с Tool Calling. В Agent mode VS Code такие модели не показывает; выполните Model Doctor для подключения.'
}
